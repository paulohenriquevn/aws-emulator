#!/usr/bin/env python3
"""Render theo/router from theo/services.txt.

The upstream router (core/router) mounts every AWS service, which needs ~100 GB of
build output. theo/router mounts only the services listed in theo/services.txt, so
it lives outside the files the upstream scaffold re-renders and survives an
upstream sync untouched.

Usage:
    python3 theo/render_router.py           # rewrite the generated files
    python3 theo/render_router.py --check   # exit 1 if they are out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SERVICES_FILE = ROOT / "theo" / "services.txt"
ROUTER_DIR = ROOT / "theo" / "router"
UPSTREAM_MAIN = ROOT / "core" / "router" / "src" / "main.rs"

# Services per #[inline(never)] helper. The upstream router splits registration
# the same way so no single stack frame holds every service's constructor.
CHUNK_SIZE = 5

HEADER = "// @generated by theo/render_router.py from theo/services.txt. Do not edit.\n"


class RenderError(Exception):
    """The inputs cannot produce a valid router."""


def read_services() -> list[str]:
    services = []
    for raw in SERVICES_FILE.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if not (ROOT / "services" / line).is_dir():
            raise RenderError(f"theo/services.txt names {line!r}, but services/{line} does not exist")
        services.append(line)
    if len(services) != len(set(services)):
        raise RenderError("theo/services.txt lists a service more than once")
    if not services:
        raise RenderError("theo/services.txt lists no service")
    return services


def render_cargo(services: list[str]) -> str:
    deps = "\n".join(f"{s} = {{ workspace = true }}" for s in services)
    return f"""# @generated by theo/render_router.py from theo/services.txt. Do not edit.
[package]
name = "theo-aws-emulator-router"
version.workspace = true
edition.workspace = true
license.workspace = true
publish = false

[[bin]]
name = "theo-aws-emulator"
path = "src/main.rs"

[dependencies]
engine = {{ workspace = true }}
emulator-server = {{ workspace = true }}
emulator-telemetry = {{ workspace = true }}
smithy-server-runtime = {{ workspace = true }}
aws-smithy-runtime-api = {{ workspace = true }}
aws-smithy-types = {{ workspace = true }}
tokio = {{ workspace = true }}
http = {{ workspace = true }}
bytes = {{ workspace = true }}
tracing = {{ workspace = true }}
tracing-subscriber = {{ workspace = true }}
{deps}

[lints]
workspace = true
"""


def render_lib(services: list[str]) -> str:
    chunks = [services[i : i + CHUNK_SIZE] for i in range(0, len(services), CHUNK_SIZE)]
    calls = "\n".join(f"    let router = mount_chunk_{n:02}(router, &engine);" for n in range(len(chunks)))
    helpers = []
    for n, chunk in enumerate(chunks):
        regs = "\n".join(
            f"    router.register_service({s.replace('-', '_')}::EmulatedService::new(engine.clone()));"
            for s in chunk
        )
        helpers.append(
            f"#[inline(never)]\nfn mount_chunk_{n:02}(\n    mut router: MultiServiceRouter,\n"
            f"    engine: &Arc<InMemoryEngine>,\n) -> MultiServiceRouter {{\n{regs}\n    router\n}}\n"
        )
    return (
        "// SPDX-License-Identifier: CC0-1.0\n"
        + HEADER
        + "\n#![forbid(unsafe_code)]\n"
        + "//! The services theo uses, mounted on one endpoint. See theo/README.md.\n\n"
        + "use smithy_server_runtime::MultiServiceRouter;\nuse std::sync::Arc;\npub use engine::InMemoryEngine;\n\n"
        + "/// The service crates this router mounts, in registration order.\n"
        + f"pub const MOUNTED_SERVICES: [&str; {len(services)}] = [\n"
        + "".join(f'    "{s}",\n' for s in services)
        + "];\n\n"
        + "pub fn build_router(engine: Arc<InMemoryEngine>) -> MultiServiceRouter {\n"
        + "    let router = MultiServiceRouter::new();\n"
        + calls
        + "\n    router\n}\n\n"
        + "\n".join(helpers)
    )


def render_main() -> str:
    upstream = UPSTREAM_MAIN.read_text()
    needle = "aws_emulator_router::build_router"
    if upstream.count(needle) != 1:
        raise RenderError(f"core/router/src/main.rs must call {needle} exactly once; found {upstream.count(needle)}")
    return HEADER + upstream.replace(needle, "theo_aws_emulator_router::build_router")


def rendered() -> dict[Path, str]:
    services = read_services()
    return {
        ROUTER_DIR / "Cargo.toml": render_cargo(services),
        ROUTER_DIR / "src" / "lib.rs": render_lib(services),
        ROUTER_DIR / "src" / "main.rs": render_main(),
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, content in rendered().items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("out of date, run python3 theo/render_router.py:", *stale, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except RenderError as err:
        print(f"render_router: {err}", file=sys.stderr)
        sys.exit(2)
