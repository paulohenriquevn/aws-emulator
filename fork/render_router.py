#!/usr/bin/env python3
"""Render fork/router from fork/services.txt.

The upstream router (core/router) mounts every AWS service, which needs ~100 GB of
build output. fork/router mounts only the services listed in fork/services.txt, so
it lives outside the files the upstream scaffold re-renders and survives an
upstream sync untouched.

Usage:
    python3 fork/render_router.py           # rewrite the generated files
    python3 fork/render_router.py --check   # exit 1 if they are out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SERVICES_FILE = ROOT / "fork" / "services.txt"
ROUTER_DIR = ROOT / "fork" / "router"
UPSTREAM_MAIN = ROOT / "core" / "router" / "src" / "main.rs"

# Services per #[inline(never)] helper. The upstream router splits registration
# the same way so no single stack frame holds every service's constructor.
CHUNK_SIZE = 5

HEADER = "// @generated by fork/render_router.py from fork/services.txt. Do not edit.\n"


class RenderError(Exception):
    """The inputs cannot produce a valid router."""


def read_services() -> list[str]:
    services = []
    for raw in SERVICES_FILE.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if not (ROOT / "services" / line).is_dir():
            raise RenderError(f"fork/services.txt names {line!r}, but services/{line} does not exist")
        services.append(line)
    if len(services) != len(set(services)):
        raise RenderError("fork/services.txt lists a service more than once")
    if not services:
        raise RenderError("fork/services.txt lists no service")
    return services


def render_cargo(services: list[str]) -> str:
    deps = "\n".join(f"{s} = {{ workspace = true }}" for s in services)
    return f"""# @generated by fork/render_router.py from fork/services.txt. Do not edit.
[package]
name = "aws-emulator-fork-router"
version.workspace = true
edition.workspace = true
license.workspace = true
publish = false

[[bin]]
name = "aws-emulator-fork"
path = "src/main.rs"

[dependencies]
aws-emulator-fork-console = {{ workspace = true }}
aws-emulator-fork-service-account-issuers = {{ workspace = true }}
aws-emulator-fork-eks-control-plane = {{ workspace = true }}
aws-emulator-fork-access-log = {{ workspace = true }}
aws-emulator-fork-iam-gate = {{ workspace = true }}
engine = {{ workspace = true }}
emulator-server = {{ workspace = true }}
emulator-telemetry = {{ workspace = true }}
smithy-server-runtime = {{ workspace = true }}
aws-smithy-runtime-api = {{ workspace = true }}
aws-smithy-types = {{ workspace = true }}
tokio = {{ workspace = true }}
http = {{ workspace = true }}
bytes = {{ workspace = true }}
tracing = {{ workspace = true }}
tracing-subscriber = {{ workspace = true }}
{deps}

[dev-dependencies]
rustls = {{ workspace = true }}
serde_json = {{ workspace = true }}
ring = "0.17"

[lints]
workspace = true
"""


def render_lib(services: list[str]) -> str:
    chunks = [services[i : i + CHUNK_SIZE] for i in range(0, len(services), CHUNK_SIZE)]
    calls = "\n".join(f"    let router = mount_chunk_{n:02}(router, &engine);" for n in range(len(chunks)))
    helpers = []
    for n, chunk in enumerate(chunks):
        regs = "\n".join(
            f"    router.register_service({s.replace('-', '_')}::EmulatedService::new(engine.clone()));"
            for s in chunk
        )
        helpers.append(
            f"#[inline(never)]\nfn mount_chunk_{n:02}(\n    mut router: MultiServiceRouter,\n"
            f"    engine: &Arc<InMemoryEngine>,\n) -> MultiServiceRouter {{\n{regs}\n    router\n}}\n"
        )
    return (
        "// SPDX-License-Identifier: CC0-1.0\n"
        + HEADER
        + "\n#![forbid(unsafe_code)]\n"
        + "//! The services this fork mounts, on one endpoint, and the read-only console at\n"
        + "//! `/_console/`. See fork/README.md.\n\n"
        + "use emulator_server::WithExtraRoutes;\nuse smithy_server_runtime::MultiServiceRouter;\n"
        + "use std::sync::Arc;\npub use engine::InMemoryEngine;\n\n"
        + "/// The service crates this router mounts, in registration order.\n"
        + f"pub const MOUNTED_SERVICES: [&str; {len(services)}] = [\n"
        + "".join(f'    "{s}",\n' for s in services)
        + "];\n\n"
        + "/// The mounted services behind the fork's own routes, which are answered before\n"
        + "/// service dispatch: the console, and the registration of an external cluster's\n"
        + "/// service account key set and of an external control plane (each checks its own\n"
        + "/// SigV4 signature). Every other request falls through to the services.\n"
        + "pub fn build_router(engine: Arc<InMemoryEngine>) -> WithExtraRoutes<MultiServiceRouter> {\n"
        + "    let issuers = Arc::clone(&engine);\n"
        + "    let control_planes = Arc::clone(&engine);\n"
        + "    WithExtraRoutes::new(build_services(engine))\n"
        + "        .route_matching(aws_emulator_fork_console::claims, |request| async move {\n"
        + "            aws_emulator_fork_console::respond(&request)\n"
        + "        })\n"
        + "        .route_matching(aws_emulator_fork_service_account_issuers::claims, move |request| {\n"
        + "            let engine = Arc::clone(&issuers);\n"
        + "            async move { aws_emulator_fork_service_account_issuers::respond(&engine, &request) }\n"
        + "        })\n"
        + "        .route_matching(aws_emulator_fork_eks_control_plane::claims, move |request| {\n"
        + "            let engine = Arc::clone(&control_planes);\n"
        + "            async move { aws_emulator_fork_eks_control_plane::respond(&engine, &request) }\n"
        + "        })\n}\n\n"
        + "/// The mounted services alone, without the console route. Tests use it to turn\n"
        + "/// request authentication off and call `dispatch` directly.\n"
        + "pub fn build_services(engine: Arc<InMemoryEngine>) -> MultiServiceRouter {\n"
        + "    let router = MultiServiceRouter::new();\n"
        + calls
        + "\n    let mut router = router;\n"
        + "    if aws_emulator_fork_iam_gate::enforce_enabled(\n"
        + "        std::env::var(aws_emulator_fork_iam_gate::ENFORCE_ENV).ok().as_deref(),\n"
        + "    ) {\n"
        + "        aws_emulator_fork_iam_gate::install(&mut router, Arc::clone(&engine));\n"
        + "    }\n"
        + "    router\n}\n\n"
        + "\n".join(helpers)
    )


def render_main() -> str:
    upstream = UPSTREAM_MAIN.read_text()
    needle = "aws_emulator_router::build_router(engine)"
    if upstream.count(needle) != 1:
        raise RenderError(f"core/router/src/main.rs must call {needle} exactly once; found {upstream.count(needle)}")
    # Every request is answered through the access log (fork/access-log).
    return HEADER + upstream.replace(
        needle, "aws_emulator_fork_access_log::AccessLog::new(aws_emulator_fork_router::build_router(engine))"
    )


def rendered() -> dict[Path, str]:
    services = read_services()
    return {
        ROUTER_DIR / "Cargo.toml": render_cargo(services),
        ROUTER_DIR / "src" / "lib.rs": render_lib(services),
        ROUTER_DIR / "src" / "main.rs": render_main(),
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, content in rendered().items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("out of date, run python3 fork/render_router.py:", *stale, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except RenderError as err:
        print(f"render_router: {err}", file=sys.stderr)
        sys.exit(2)
