//! fork: every state an instance moves into, published on EventBridge.
//!
//! "Amazon EC2 sends an EC2 Instance State-change Notification event to Amazon EventBridge
//! when the state of an instance changes" (EC2 User Guide, "Amazon EventBridge events for
//! Amazon EC2 instance state changes"). The event goes to the account's default bus with
//! `source` `aws.ec2`, `detail` `{"instance-id", "state"}` and the instance ARN in
//! `resources`. Cluster API Provider AWS can read instance state from these events.
//!
//! An instance changes state in two ways here: a call moves it (`RunInstances`,
//! `StopInstances`, `StartInstances`, a termination), and the clock moves it on when the
//! transition a call left owed falls due. Each change is queued on the store where it
//! happens ([`InstanceStateEvents`]), so no state is skipped even when a later call moves the
//! instance again before anyone publishes.
//!
//! Two paths drain the queue. Every EC2 call publishes what is queued once it has answered
//! (`crate::service`). A clock-owed change is published by an in-process task
//! ([`drive_instance_state_clock`]) that wakes when the earliest owed transition falls due,
//! so a client watching the bus sees `running` without calling EC2 again.
//!
//! Publication goes through the in-process EventBridge client
//! ([`service_common::eventbridge_client`]) like the Auto Scaling lifecycle events. It is
//! best effort: with no EventBridge mounted, or a call that fails, the events are logged and
//! dropped, and EC2 answers as it would have.

use std::collections::VecDeque;
use std::sync::Arc;
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

use super::{instance_region, ComAmazonawsEc2Amazonec2State, InstanceRecord, InstanceStateName};

/// The `source` EC2 publishes its own events under.
pub const EVENT_SOURCE: &str = "aws.ec2";

/// The `detail-type` of an instance state change.
pub const STATE_CHANGE_DETAIL_TYPE: &str = "EC2 Instance State-change Notification";

/// "Events generated by AWS services go to your account's default event bus."
const DEFAULT_EVENT_BUS: &str = "default";

/// The most entries one `PutEvents` request carries (`PutEventsRequest$Entries`).
const MAX_PUT_EVENTS_ENTRIES: usize = 10;

/// How many unpublished state changes the queue holds. This module's own bound, not an AWS
/// quota: the queue lives in memory, so the oldest change is dropped first.
pub const MAX_QUEUED_STATE_EVENTS: usize = 10_000;

/// The clock task's bounds: it never spins (a wake-up always waits at least the minimum),
/// never sleeps past a transition by more than the maximum, and stops after the wake-up cap
/// even if the store keeps owing transitions; the next EC2 call starts a new one.
const MIN_CLOCK_WAIT: Duration = Duration::from_millis(20);
const MAX_CLOCK_WAIT: Duration = Duration::from_secs(5);
const MAX_CLOCK_WAKE_UPS: usize = 10_000;

/// One state an instance moved into, not yet published.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InstanceStateEvent {
    pub instance_id: String,
    pub region: String,
    pub state: InstanceStateName,
    /// When the instance moved, which is the event's `time`.
    pub at: SystemTime,
}

impl InstanceStateEvent {
    /// The state `instance` is in now, moved into at `at`.
    pub fn of(instance: &InstanceRecord, at: SystemTime) -> Self {
        Self {
            instance_id: instance.instance_id.clone(),
            region: instance_region(instance).to_string(),
            state: instance.state,
            at,
        }
    }

    /// The event's `detail`, as the EC2 User Guide documents it.
    pub fn detail(&self) -> serde_json::Value {
        serde_json::json!({ "instance-id": self.instance_id, "state": self.state.as_str() })
    }
}

/// The store's queue of unpublished state changes and the claim of its clock task.
#[derive(Debug, Default)]
pub struct InstanceStateEvents {
    queued: VecDeque<InstanceStateEvent>,
    clock_running: bool,
}

impl InstanceStateEvents {
    /// Queue `event`, dropping the oldest one when the queue is full.
    pub fn push(&mut self, event: InstanceStateEvent) {
        if self.queued.len() >= MAX_QUEUED_STATE_EVENTS {
            let dropped = self.queued.pop_front();
            ::tracing::warn!(?dropped, "EC2 instance state event queue full; dropped the oldest event");
        }
        self.queued.push_back(event);
    }

    /// Take every queued event, oldest first.
    pub fn take(&mut self) -> Vec<InstanceStateEvent> {
        self.queued.drain(..).collect()
    }
}

/// When the clock-owed transition that was due at `due_at` happened, as wall-clock time.
pub fn moved_at(due_at: Instant, now: Instant) -> SystemTime {
    let late_by = now.saturating_duration_since(due_at);
    SystemTime::now().checked_sub(late_by).unwrap_or_else(SystemTime::now)
}

impl ComAmazonawsEc2Amazonec2State {
    /// Queue the state instance `instance_id` is in now, moved into just now.
    pub fn note_instance_state(&mut self, instance_id: &str) {
        if let Some(instance) = self.instances.get(instance_id) {
            self.instance_state_events
                .push(InstanceStateEvent::of(instance, SystemTime::now()));
        }
    }

    /// The earliest instant the clock owes any instance a transition.
    pub fn next_instance_transition_due(&self) -> Option<Instant> {
        self.instances
            .values()
            .filter_map(|instance| instance.pending_transition.as_ref().map(|pending| pending.due_at))
            .min()
    }
}

/// Publish every queued state change. Called with no lock held.
pub async fn publish_instance_state_events<Eng: Send + Sync + 'static>(
    callback: &smithy_server_runtime::EmbeddedEmulator,
    engine: &Eng,
) {
    let Some(state) = super::service_state(engine) else {
        return;
    };
    let events = state.lock().instance_state_events.take();
    publish(callback, &events).await;
}

/// Apply the transitions the clock owes, then publish what they and any call queued.
async fn publish_due<Eng: Send + Sync + 'static>(
    callback: &smithy_server_runtime::EmbeddedEmulator,
    engine: &Eng,
) {
    let Some(state) = super::service_state(engine) else {
        return;
    };
    let events = {
        let mut store = state.lock();
        store.materialize_due_transitions();
        store.instance_state_events.take()
    };
    publish(callback, &events).await;
}

/// `PutEvents` for `events`, one request per Region and per [`MAX_PUT_EVENTS_ENTRIES`].
async fn publish(callback: &smithy_server_runtime::EmbeddedEmulator, events: &[InstanceStateEvent]) {
    let mut regions: Vec<&str> = events.iter().map(|event| event.region.as_str()).collect();
    regions.sort_unstable();
    regions.dedup();
    for region in regions {
        let client = ::service_common::eventbridge_client::eventbridge_client(callback, region);
        let of_region: Vec<&InstanceStateEvent> = events.iter().filter(|event| event.region == region).collect();
        for window in of_region.chunks(MAX_PUT_EVENTS_ENTRIES) {
            let mut request = client.put_events();
            for event in window {
                request = request.entries(
                    ::aws_sdk_eventbridge::types::PutEventsRequestEntry::builder()
                        .event_bus_name(DEFAULT_EVENT_BUS)
                        .source(EVENT_SOURCE)
                        .detail_type(STATE_CHANGE_DETAIL_TYPE)
                        .time(::aws_sdk_eventbridge::primitives::DateTime::from_millis(epoch_millis(event.at)))
                        .resources(::engine::emulator_arn("ec2", region, &format!("instance/{}", event.instance_id)))
                        .detail(event.detail().to_string())
                        .build(),
                );
            }
            let instances: Vec<&str> = window.iter().map(|event| event.instance_id.as_str()).collect();
            match request.send().await {
                Ok(output) if output.failed_entry_count() > 0 => {
                    ::tracing::warn!(
                        region,
                        instances = ?instances,
                        entries = ?output.entries(),
                        "EventBridge refused some EC2 instance state events"
                    );
                }
                Ok(_) => {}
                Err(error) => {
                    ::tracing::warn!(
                        error = %::aws_smithy_types::error::display::DisplayErrorContext(&error),
                        region,
                        instances = ?instances,
                        "EC2 instance state events could not be published to EventBridge"
                    );
                }
            }
        }
    }
}

fn epoch_millis(at: SystemTime) -> i64 {
    i64::try_from(at.duration_since(UNIX_EPOCH).unwrap_or_default().as_millis()).unwrap_or_default()
}

/// Start the clock task when the store owes a transition and none is running.
///
/// The task waits for the earliest owed transition, applies it and publishes, and stops as
/// soon as nothing is owed; the check and the release happen under one lock, so a call that
/// owes a new transition afterwards finds no claim and starts a task of its own. With no
/// async runtime there is no task, and the next EC2 call applies and publishes instead.
pub fn drive_instance_state_clock<Eng: Send + Sync + 'static>(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    engine: &Arc<Eng>,
) {
    let Some(state) = super::service_state(&**engine) else {
        return;
    };
    let Ok(runtime) = ::tokio::runtime::Handle::try_current() else {
        return;
    };
    {
        let mut store = state.lock();
        if store.instance_state_events.clock_running || store.next_instance_transition_due().is_none() {
            return;
        }
        store.instance_state_events.clock_running = true;
    }
    let callback = ctx.callback().clone();
    let engine = Arc::clone(engine);
    runtime.spawn(async move {
        for _ in 0..MAX_CLOCK_WAKE_UPS {
            let due = {
                let mut store = state.lock();
                match store.next_instance_transition_due() {
                    Some(due) => due,
                    None => {
                        store.instance_state_events.clock_running = false;
                        return;
                    }
                }
            };
            let wait = due
                .saturating_duration_since(Instant::now())
                .clamp(MIN_CLOCK_WAIT, MAX_CLOCK_WAIT);
            ::tokio::time::sleep(wait).await;
            publish_due(&callback, &*engine).await;
        }
        state.lock().instance_state_events.clock_running = false;
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    fn event(id: &str) -> InstanceStateEvent {
        InstanceStateEvent {
            instance_id: id.to_string(),
            region: "us-east-1".to_string(),
            state: InstanceStateName::Pending,
            at: UNIX_EPOCH,
        }
    }

    #[test]
    fn the_queue_hands_back_events_oldest_first_and_empties() {
        let mut queue = InstanceStateEvents::default();
        queue.push(event("i-1"));
        queue.push(event("i-2"));

        let taken = queue.take();

        assert_eq!(taken, [event("i-1"), event("i-2")]);
        assert!(queue.take().is_empty());
    }

    #[test]
    fn a_full_queue_drops_its_oldest_event() {
        let mut queue = InstanceStateEvents::default();
        for index in 0..=MAX_QUEUED_STATE_EVENTS {
            queue.push(event(&format!("i-{index}")));
        }

        let taken = queue.take();

        assert_eq!(taken.len(), MAX_QUEUED_STATE_EVENTS);
        assert_eq!(taken[0].instance_id, "i-1");
    }

    #[test]
    fn the_detail_names_the_instance_and_its_state_as_documented() {
        let detail = event("i-0abc").detail();

        assert_eq!(detail, serde_json::json!({"instance-id": "i-0abc", "state": "pending"}));
    }

    #[test]
    fn a_transition_applied_late_is_dated_when_it_fell_due() {
        let now = Instant::now();
        let due = now - Duration::from_secs(3);

        let at = moved_at(due, now);

        let age = SystemTime::now().duration_since(at).expect("in the past");
        assert!(age >= Duration::from_secs(3) && age < Duration::from_secs(4), "{age:?}");
    }
}
